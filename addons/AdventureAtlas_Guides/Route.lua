-- the segment chain of a race: its start segments, then the shared path (the Undead join it at
-- h-13-silverpine on foot, every other race at h-12-orgrimmar-tirisfal)
local function chain(r, start)
    local list = {}
    for j = 1, #start do list[#list + 1] = start[j] end
    if r.visit then list[#list + 1] = VISIT end
    for j = 1, #SILVERPINE_ON do list[#list + 1] = SILVERPINE_ON[j] end
    return list
end

for i = 1, #RACES do
    local r = RACES[i]
    local start = ns.startZones and ns.startZones[r.zone] -- announced by the zone's last segment file
    if start then
        local segments = chain(r, start)
        local only
        if start.only then
            only = {}
            for j = 1, #start.only do only[start.only[j]] = true end
        end
        for j = 1, #r.classes do
            local class = r.classes[j]
            if not only or only[class] then
                local c = CLASSES[class]
                local id = r.slug .. "-" .. c.slug
                AdventureAtlas.RegisterRoute({
                    api = 1,
                    id = id,
                    title = { ru = r.ru .. "-" .. c.ru .. " 1-60", en = r.en .. " " .. c.en .. " 1-60" },
                    description = {
                        ru = r.ru .. "-" .. c.ru .. ", скоростная прокачка 1-60: " .. r.start.ru .. ", " .. PATH.ru,
                        en = r.en .. " " .. c.en .. ", speed leveling 1-60: " .. r.start.en .. ", " .. PATH.en,
                    },
                    faction = "Horde",
                    races = { r.race },
                    classes = { class },
                    levels = { 1, 60 },
                    version = "0.4.0",
                    author = "AdventureAtlas",
                    default = true,
                    aliases = r.aliases and r.aliases[class] or nil,
                })
                AdventureAtlas.UseSegments(id, segments)
            end
        end
    end
end
