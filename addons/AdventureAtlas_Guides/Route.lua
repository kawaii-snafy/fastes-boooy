-- AdventureAtlas_Guides / Route.lua
-- The routes of the module: one guide per race and class, id "<race>-<class>", registered from one table.
-- Routes own nothing: every segment is a shared segment (Segments/**), every class and race step a shared
-- insert (Classes/*.lua, Races/*.lua). This is the last file of the TOC.
--
-- A race gets its routes only when its start zone has announced itself: the last segment file of the zone sets
--   ns.startZones.<Zone> = { "<segment id>", ..., only = { "<CLASS>", ... } }
-- (keys Tirisfal, Zephras, Durotar, Mulgore; the array part is the list of start segments; while `only` is
-- present, only these classes of the zone's races are registered). A zone whose files are placeholders announces
-- nothing, so no route of its races exists.
--
-- Data.lua is generated by tools/gen_route_data.lua (make routedata).
