-- Widget behaviour, UI helpers, Settings, static popups and chat output of the WoW: Forever mock.

local Mock = require("mocks.wow")

describe("mock widgets", function()
    local m, env

    before_each(function()
        m = Mock.new()
        env = m.env
    end)

    after_each(function() m:AssertClean() end)

    it("stores anchors, sizes, scale and alpha", function()
        local f = env.CreateFrame("Frame", "TestPanel", env.UIParent)
        f:SetSize(200, 100)
        f:SetPoint("TOPLEFT", env.UIParent, "TOPLEFT", 10, -20)
        f:SetPoint("CENTER", 5, 5)
        assert.are.equal(2, f:GetNumPoints())
        assert.are.same({ "TOPLEFT", env.UIParent, "TOPLEFT", 10, -20 }, { f:GetPoint(1) })
        assert.are.same({ "CENTER", env.UIParent, "CENTER", 5, 5 }, { f:GetPoint(2) })
        f:SetPoint("TOPLEFT", "UIParent", "BOTTOMLEFT")         -- replaces the TOPLEFT point, name lookup
        assert.are.equal("BOTTOMLEFT", select(3, f:GetPoint(2)))
        f:ClearAllPoints()
        assert.are.equal(0, f:GetNumPoints())
        assert.are.same({ 200, 100 }, { f:GetSize() })
        f:SetScale(2)
        assert.are.equal(2, f:GetEffectiveScale())
        f:SetAlpha(1.5)
        assert.are.equal(1, f:GetAlpha())
        local tex = f:CreateTexture(nil, "BACKGROUND")
        tex:SetAllPoints(f)
        assert.are.equal(200, tex:GetWidth())
        assert.are.equal(f, tex:GetParent())
        assert.are.equal(1, f:GetNumRegions())
        assert.are.equal("Texture", tex:GetObjectType())
        assert.is_true(tex:IsObjectType("Region"))
    end)

    it("keeps generic setter state readable through the matching getter", function()
        local f = env.CreateFrame("Frame")
        f:SetMovable(true)
        f:SetClampedToScreen(true)
        f:EnableMouse(true)
        f:SetFrameStrata("DIALOG")
        f:SetFrameLevel(7)
        f:SetID(3)
        assert.is_true(f:IsMovable())
        assert.is_true(f:IsClampedToScreen())
        assert.is_true(f:IsMouseEnabled())
        assert.are.equal("DIALOG", f:GetFrameStrata())
        assert.are.equal(7, f:GetFrameLevel())
        assert.are.equal(3, f:GetID())
        local child = env.CreateFrame("Frame", nil, f)
        assert.are.equal("DIALOG", child:GetFrameStrata())
        assert.are.equal(8, child:GetFrameLevel())
        assert.are.same({ child }, { f:GetChildren() })
    end)

    it("handles font strings and text", function()
        local f = env.CreateFrame("Frame", nil, env.UIParent)
        local fs = f:CreateFontString(nil, "OVERLAY", "GameFontHighlightSmall")
        assert.are.equal(env.GameFontHighlightSmall, fs:GetFontObject())
        assert.is_nil(fs:GetText())
        fs:SetText("Kill 8 zombies")
        assert.are.equal("Kill 8 zombies", fs:GetText())
        fs:SetFormattedText("%d/%d", 3, 8)
        assert.are.equal("3/8", fs:GetText())
        fs:SetText(42)
        assert.are.equal("42", fs:GetText())
        assert.has_error(function() fs:SetText({}) end)
        fs:SetText("line1\nline two")
        assert.are.equal(2, fs:GetNumLines())
        assert.are.equal(48, fs:GetStringWidth())
        fs:SetTextColor(1, 0.5, 0)
        assert.are.same({ 1, 0.5, 0, 1 }, { fs:GetTextColor() })
        fs:SetJustifyH("LEFT")
        assert.has_error(function() fs:SetJustifyH("MIDDLE") end)
        assert.are.same({ "line1\nline two" }, m:VisibleTexts())
        local font = env.CreateFont("MyAddonFont")
        assert.are.equal(font, env.MyAddonFont)
        fs:SetFontObject("MyAddonFont")
        assert.are.equal(font, fs:GetFontObject())
    end)

    it("clicks buttons and toggles check buttons", function()
        local clicks = {}
        local b = env.CreateFrame("Button", nil, env.UIParent)
        b:SetScript("OnClick", function(_, button, down) clicks[#clicks + 1] = { button, down } end)
        m:Click(b)
        b:Disable()
        m:Click(b)
        assert.are.same({ { "LeftButton", false } }, clicks)
        b:SetText("Skip")
        assert.are.equal("Skip", b:GetText())
        local cb = env.CreateFrame("CheckButton", nil, env.UIParent, "UICheckButtonTemplate")
        local state
        cb:SetScript("OnClick", function(self) state = self:GetChecked() end)
        m:Click(cb)
        assert.is_true(state)
        m:Click(cb)
        assert.is_false(state)
        cb:SetChecked(true)
        assert.is_true(cb:GetChecked())
    end)

    it("fires OnValueChanged for sliders and status bars", function()
        local values = {}
        local s = env.CreateFrame("Slider", nil, env.UIParent, "UISliderTemplate")
        s:SetScript("OnValueChanged", function(_, v, user) values[#values + 1] = { v, user } end)
        s:SetMinMaxValues(0.5, 2)
        s:SetValueStep(0.05)
        s:SetObeyStepOnDrag(true)
        s:SetValue(1)
        s:SetValue(1)
        s:SetValue(5)
        m:DragSlider(s, 1.23)
        assert.are.same({ { 0.5, false }, { 1, false }, { 2, false } }, { values[1], values[2], values[3] })
        assert.is_true(math.abs(values[4][1] - 1.25) < 1e-9)
        assert.is_true(values[4][2])
        local bar = env.CreateFrame("StatusBar", nil, env.UIParent)
        bar:SetMinMaxValues(0, 400)
        bar:SetValue(150)
        assert.are.equal(150, bar:GetValue())
        bar:SetStatusBarTexture("Interface\\TargetingFrame\\UI-StatusBar")
        assert.are.equal("Texture", bar:GetStatusBarTexture():GetObjectType())
    end)

    it("handles edit boxes, focus and scroll children", function()
        local events = {}
        local scroll = env.CreateFrame("ScrollFrame", nil, env.UIParent, "UIPanelScrollFrameTemplate")
        local edit = env.CreateFrame("EditBox", nil, scroll)
        scroll:SetScrollChild(edit)
        assert.are.equal(edit, scroll:GetScrollChild())
        edit:SetScript("OnTextChanged", function(_, user) events[#events + 1] = user end)
        edit:SetMultiLine(true)
        edit:SetText("363=80")
        m:TypeText(edit, "x")
        assert.are.same({ false, true }, events)
        assert.are.equal("363=80x", edit:GetText())
        assert.is_true(edit:IsMultiLine())
        assert.is_true(edit:IsAutoFocus())
        edit:SetFocus()
        assert.is_true(edit:HasFocus())
        assert.are.equal(edit, env.GetCurrentKeyBoardFocus())
        edit:ClearFocus()
        assert.is_false(edit:HasFocus())
    end)

    it("shows tooltips from UIPanelButtonTemplate.tooltipText and records the lines", function()
        local b = env.CreateFrame("Button", nil, env.UIParent, "UIPanelButtonTemplate")
        b.tooltipText = "Next step"
        m:Enter(b)
        assert.is_true(env.GameTooltip:IsShown())
        assert.are.equal(b, env.GameTooltip:GetOwner())
        env.GameTooltip:AddLine("detail", 1, 1, 1, true)
        env.GameTooltip:AddDoubleLine("left", "right")
        assert.are.same({ "Next step", "detail", "left | right" }, m:TooltipLines())
        m:Leave(b)
        assert.is_false(env.GameTooltip:IsShown())
        assert.are.equal(0, env.GameTooltip:NumLines())
        assert.has_error(function() env.GameTooltip:SetOwner(b, "ANCHOR_WEIRD") end)
    end)

    it("names template children after named parents ($parent)", function()
        local s = env.CreateFrame("Slider", "MySlider", env.UIParent, "OptionsSliderTemplate")
        assert.are.equal(s.Low, env.MySliderLow)
        assert.are.equal(s.Text, env.MySliderText)
        local anon = env.CreateFrame("Slider", nil, env.UIParent, "OptionsSliderTemplate")
        assert.is_table(anon.High)
        assert.is_nil(anon.High:GetName())
    end)
end)

describe("mock UI services", function()
    local m, env

    before_each(function()
        m = Mock.new()
        env = m.env
    end)

    after_each(function() m:AssertClean() end)

    it("registers and opens a canvas Settings category", function()
        local panel = env.CreateFrame("Frame")
        panel:Hide()
        local shown = false
        panel:SetScript("OnShow", function() shown = true end)
        local category = env.Settings.RegisterCanvasLayoutCategory(panel, "AdventureAtlas")
        env.Settings.RegisterAddOnCategory(category)
        assert.is_number(category:GetID())
        assert.are.equal("AdventureAtlas", category:GetName())
        assert.is_true(env.Settings.OpenToCategory(category:GetID()))
        assert.is_true(shown)
        assert.are.equal(category:GetID(), m.settingsOpened)
        assert.has_error(function() env.Settings.RegisterAddOnCategory({}) end)
        m:ClearDiagnostics()
    end)

    it("shows static popups and clicks their buttons", function()
        local accepted
        env.StaticPopupDialogs.TEST_RESET = {
            text = "Reset?", button1 = "Yes", button2 = "No",
            OnAccept = function(_, data) accepted = data end,
        }
        assert.is_nil(env.StaticPopup_Show("UNKNOWN_POPUP"))
        local dialog = env.StaticPopup_Show("TEST_RESET", nil, nil, "payload")
        assert.is_table(dialog)
        assert.is_true(m:PopupVisible("TEST_RESET"))
        assert.is_true(m:PopupClick("TEST_RESET", "button1"))
        assert.are.equal("payload", accepted)
        assert.is_false(m:PopupVisible("TEST_RESET"))
    end)

    it("records chat output from print and DEFAULT_CHAT_FRAME", function()
        env.print("a", 1, nil)
        env.DEFAULT_CHAT_FRAME:AddMessage("|cff33ff99FB|r: hello", 1, 1, 0)
        assert.are.same({ "a 1 nil", "|cff33ff99FB|r: hello" }, m.chat)
        assert.are.same({ 1, 1, 0 }, m.chatColors[2])
    end)

    it("blocks restricted calls on protected frames during combat lockdown", function()
        local panel = env.CreateFrame("Frame", nil, env.UIParent)
        local holder = env.CreateFrame("Frame", nil, env.UIParent)
        local other = env.CreateFrame("Frame", nil, env.UIParent)
        local b = env.CreateFrame("Button", "TestSecure", holder, "SecureActionButtonTemplate")
        assert.are.same({ true, true }, { b:IsProtected() })
        assert.are.same({ true, false }, { holder:IsProtected() }, "parent of a protected frame: implicit")
        assert.are.same({ false, false }, { panel:IsProtected() })
        b:SetPoint("CENTER", other, "CENTER")
        assert.is_true((other:IsProtected()), "a protected frame is anchored to it")
        b:SetAttribute("type", "item")                              -- fine out of combat
        m:EnterCombat()
        assert.is_false(b:CanChangeProtectedState())
        assert.is_true(panel:CanChangeProtectedState())
        assert.has_no.errors(function() panel:Hide(); panel:Show(); panel:SetHeight(10) end)
        assert.has_error(function() b:SetAttribute("item", "item:1") end)
        assert.has_error(function() b:Hide() end)
        assert.has_error(function() holder:Hide() end)
        assert.has_error(function() other:SetPoint("TOP", env.UIParent, "TOP") end)
        assert.are.equal(4, #m.violations)
        assert.matches("ADDON_ACTION_BLOCKED: Button:SetAttribute%(%) on the protected frame TestSecure", m.violations[1])
        m:ClearDiagnostics()
        m:LeaveCombat()
        assert.has_no.errors(function() b:Hide(); holder:Hide(); b:SetAttribute("item", "item:1") end)
    end)

    it("runs the secure action of a SecureActionButtonTemplate on the press or the release", function()
        local b = env.CreateFrame("Button", nil, env.UIParent, "SecureActionButtonTemplate")
        b:SetAttribute("type1", "item")
        b:SetAttribute("item1", "item:3264")
        m:Click(b)
        assert.are.same({}, m:Actions("SecureAction"), "default LeftButtonUp: ActionButtonUseKeyDown ignores the release")
        b:RegisterForClicks("AnyUp", "AnyDown")
        m:Click(b)
        assert.are.same({ { "SecureAction", "item", "item:3264", "LeftButton" } }, m:Actions("SecureAction"))
        m:Click(b, "RightButton")
        assert.are.equal(1, #m:Actions("SecureAction"), "type1 / item1: left button only")
        m.actionButtonUseKeyDown = false
        m:Click(b)
        assert.are.equal(2, #m:Actions("SecureAction"), "on the release when the CVar is off, once")
        b:SetScript("OnClick", function() end)
        m:Click(b)
        assert.are.equal(2, #m:Actions("SecureAction"), "a replaced OnClick loses the secure action")
    end)

    it("hooks functions with hooksecurefunc and keeps the original results", function()
        local seen
        local t = { Do = function(x) return x * 2 end }
        env.hooksecurefunc(t, "Do", function(x) seen = x end)
        assert.are.equal(10, t.Do(5))
        assert.are.equal(5, seen)
    end)
end)
