-- Engine progression on the strict mock with the test route: cursor, background list,
-- optional steps, transient observations, fast-forward on a cold start with EMPTY
-- SavedVariables, manual navigation (Next / Prev / Skip / SetCursor / Reset) and
-- persistence across /reload.

local H = require("fixtures.core.helpers")

local m, ns
local PIT = H.Mock.allowlist.enums.PlayerInteractionType

local function E() return ns.Engine end
local function idx(id) return H.INDEX[id] end

describe("engine", function()
    after_each(function()
        if m then m:AssertClean() end
        m, ns = nil, nil
    end)

    it("filters the route for the character and starts on the first step", function()
        m, ns = H.boot()
        assert.same(H.STEP_IDS, H.ids(E():GetSteps()))
        assert.equal(1, E():GetCursor())
        assert.equal(1, E():GetNaturalCursor())
        assert.is_false(E():IsPinned())
        assert.equal("tr-accept-363", H.cur(ns))
        assert.same({}, E():GetBackground())
        assert.same({ "tr-363-364", "tr-bg-364", "tr-train-1" }, H.ids(E():GetUpcoming(3)))
        assert.equal(4, #E():GetUpcoming(), "default: settings.shownNext")
        assert.is_nil(E():IndexOf("tr-warrior"), "class filter")
        assert.is_nil(E():IndexOf("tr-troll"), "race filter")
        assert.is_nil(E():IndexOf("tr-alliance"), "faction filter")
        assert.equal(idx("tr-accept-376"), E():IndexOf("tr-accept-376"))
    end)

    it("follows the quest log and keeps background goals 'along the way'", function()
        m, ns = H.boot()
        local changed = H.record(ns, "STEP_CHANGED")
        local progress = H.record(ns, "PROGRESS_UPDATED")
        m:AddQuestToLog(363)
        H.settle(m)
        assert.equal("tr-363-364", H.cur(ns))
        assert.equal("tr-363-364", changed[#changed][1].id)
        assert.equal(2, changed[#changed][2])
        assert.is_true(#progress >= 1)
        m:TurnInQuest(363)
        m:AddQuestToLog(364)
        H.settle(m)
        assert.equal("tr-train-1", H.cur(ns), "bg step 3 does not block")
        assert.same({ "tr-bg-364" }, H.ids(E():GetBackground()))
        assert.is_false(E():IsDone("tr-bg-364"))
        m:ProgressObjective(364, 1, 5)
        H.settle(m)
        assert.is_true(E():IsDone("tr-bg-364"))
        assert.same({}, E():GetBackground())
        assert.equal("tr-train-1", H.cur(ns))
    end)

    it("drops a background goal whose quest the player abandoned and keeps the cursor (quest given up)", function()
        m, ns = H.boot()
        local cdb = m.env.AdventureAtlasCharDB
        H.playTo(m, ns, "tr-train-1")
        assert.same({ "tr-bg-364" }, H.ids(E():GetBackground()))
        local mark = #m.chat
        m:AbandonQuest(364) -- by hand, without pressing Skip first
        H.settle(m)
        assert.same({}, E():GetBackground())
        assert.equal("tr-train-1", H.cur(ns), "no jump back to the accept of the abandoned quest")
        assert.is_true(E():IsDone("tr-363-364"))
        assert.is_nil(E():GetAcceptQuests()[364], "a given-up quest is not auto-accepted again")
        -- its single-quest step is skipped; the turn-in step also accepts 3901: not marked
        assert.is_true(cdb.skipped["tr-complete-364"])
        assert.is_nil(cdb.skipped["tr-turnin-364"])
        assert.same({ accept = "tr-363-364", steps = { "tr-complete-364" } }, cdb.gaveUp[364])
        assert.same({ 'Quest "The Mindless Ones" abandoned: its steps are skipped (/aa prev to go back).' },
            H.chat(m, mark + 1))
        -- the mixed step waits only for its other action
        E():Next() -- train
        H.settle(m)
        assert.equal("tr-turnin-364", H.cur(ns))
        local lines = ns.Steps:Describe(E():GetCurrentStep())
        assert.same({ "turnin", "accept" }, { lines[1].kind, lines[2].kind })
        assert.is_true(lines[1].done, "turn-in of the given-up quest")
        assert.is_false(lines[2].done)
        m:AddQuestToLog(3901)
        H.settle(m)
        assert.equal("tr-level-2", H.cur(ns))
    end)

    it("keeps the cursor when the player skips a quest's step and then abandons the quest", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-complete-364")
        E():Skip()
        H.settle(m)
        assert.equal("tr-turnin-364", H.cur(ns))
        m:AbandonQuest(364)
        H.settle(m)
        assert.equal("tr-turnin-364", H.cur(ns), "the given-up quest does not send the cursor back")
        assert.is_true(E():IsDone("tr-363-364"))
        assert.is_nil(E():GetAcceptQuests()[364], "a given-up quest is not auto-accepted again")
        assert.same({}, E():GetBackground())
        -- the description agrees with the evaluation
        local lines = ns.Steps:Describe(E():GetSteps()[idx("tr-363-364")])
        assert.equal("accept", lines[2].kind)
        assert.is_true(lines[2].done)
        -- Prev un-marks the skipped step: the quest is needed again, back to its accept
        E():Prev()
        H.settle(m)
        assert.is_false(E():IsPinned())
        assert.equal("tr-363-364", H.cur(ns))
    end)

    it("leaves the route's own `abandon` step alone when the player abandons that quest by hand", function()
        m, ns = H.boot()
        local cdb = m.env.AdventureAtlasCharDB
        H.playTo(m, ns, "tr-abandon-3902")
        local mark = #m.chat
        m:AbandonQuest(3902) -- what the step asks for
        H.settle(m, 1)
        assert.equal("tr-complete-380", H.cur(ns))
        assert.is_nil(cdb.gaveUp[3902])
        assert.same({}, cdb.skipped)
        assert.same({}, H.chat(m, mark + 1))

        -- abandoned early, before the route's abandon step: the same flow as before
        m, ns = H.boot()
        cdb = m.env.AdventureAtlasCharDB
        H.playTo(m, ns, "tr-optional")
        mark = #m.chat
        m:AbandonQuest(3902)
        H.settle(m, 1)
        assert.equal("tr-optional", H.cur(ns))
        assert.is_true(E():IsDone("tr-turnin-3901-376"))
        assert.is_true(E():IsDone("tr-abandon-3902"))
        assert.is_nil(cdb.gaveUp[3902])
        assert.same({}, H.chat(m, mark + 1))
    end)

    it("keeps a quest given up by hand across /reload; a cold start rebuilds from the game state", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-train-1")
        m:AbandonQuest(364)
        H.settle(m)
        assert.equal("tr-train-1", H.cur(ns))
        local m2, ns2 = H.reload(m)
        assert.equal("tr-train-1", H.cur(ns2), "/reload: the give-up is saved")
        assert.same({ accept = "tr-363-364", steps = { "tr-complete-364" } }, m2.env.AdventureAtlasCharDB.gaveUp[364])
        assert.is_true(m2.env.AdventureAtlasCharDB.skipped["tr-complete-364"])
        assert.is_nil(ns2.Engine:GetAcceptQuests()[364])
        m2:AssertClean()
        -- empty SavedVariables: nothing in the game says the quest was given up (like a Skip)
        local m3, ns3 = H.reload(m, { coldStart = true })
        assert.equal("tr-363-364", H.cur(ns3), "the quest is not in the log: back to its accept")
        assert.same({}, m3.env.AdventureAtlasCharDB.gaveUp)
        assert.is_false(H.chatHas(m3, "abandoned"), "no give-up without a QUEST_REMOVED")
        m3:AssertClean()
        -- and the usual reconstruction still lands on the right step
        local m4, ns4 = H.boot({ player = { level = 2, xp = 600 },
            mock = { completedQuests = { 363, 364, 3901, 376 } }, setup = function(mm) mm:_addToLog(380) end })
        assert.equal("tr-turnin-3901-376", H.cur(ns4))
        assert.same({}, m4.env.AdventureAtlasCharDB.gaveUp)
        m4:AssertClean()
    end)

    it("observes transient actions only on the displayed step", function()
        m, ns = H.boot()
        -- trainer visited too early: does not count for the train step
        m:OpenTrainer({}, 244808)
        m:CloseTrainer()
        H.playTo(m, ns, "tr-train-1")
        assert.equal("tr-train-1", H.cur(ns))
        m:OpenMerchant({}, 1)
        m:CloseMerchant()
        m:OpenTaxi({}, 2)
        m:CloseTaxi()
        H.settle(m)
        assert.equal("tr-train-1", H.cur(ns), "vendor / taxi do not complete a train step")
        -- the interaction-manager event alone is enough
        m:Fire("PLAYER_INTERACTION_MANAGER_FRAME_HIDE", PIT.Trainer)
        H.settle(m)
        assert.equal("tr-complete-364", H.cur(ns))
    end)

    it("a trainer / merchant window of another NPC does not complete the step of its npc", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-vendor")
        -- Brill: the innkeeper's neighbour is a vendor too -- the step names Innkeeper Renee 5688
        m:OpenMerchant({}, 2134)
        m:CloseMerchant()
        H.settle(m)
        assert.equal("tr-vendor", H.cur(ns), "another merchant")
        m:OpenMerchant({}, 5688)
        m:CloseMerchant()
        H.settle(m)
        assert.equal("tr-train-2", H.cur(ns))
        -- the riding trainer Velma Warnam 4773 stands next to the paladin trainer Shari Stilwell 246152
        m:OpenTrainer({}, 4773)
        m:CloseTrainer()
        H.settle(m)
        assert.equal("tr-train-2", H.cur(ns), "the riding trainer does not complete the class training")
        -- a window whose NPC cannot be read (no npc unit) still counts
        m:OpenTrainer({}, nil)
        m:CloseTrainer()
        H.settle(m)
        assert.equal("tr-go-uc", H.cur(ns))
    end)

    it("forwards an optional step once a later stateful step is done", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-optional")
        assert.is_true(m.player.xp < 450, "level 2 below half of the bar")
        m:AbandonQuest(3902)
        H.settle(m)
        assert.equal("tr-optional", H.cur(ns), "abandon is no evidence of progress")
        m:CompleteObjectives(380)
        H.settle(m)
        assert.equal("tr-turnin-380", H.cur(ns))
        assert.is_true(E():IsDone("tr-optional"))
        assert.is_true(E():IsDone("tr-abandon-3902"))
    end)

    it("never moves back when a turn-in consumes collected items or a route step abandons a quest", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-turnin-3901-376")
        assert.equal(6, m:GetItemCount(3264))
        m:TurnInQuest(3901)
        m:TurnInQuest(376)
        m:AddQuestToLog(380)
        m:AddQuestToLog(3902)
        H.settle(m)
        assert.equal(0, m:GetItemCount(3264), "quest items were consumed by the turn-in")
        assert.is_true(E():IsDone("tr-collect-376"))
        assert.equal("tr-optional", H.cur(ns))
        H.playTo(m, ns, "tr-abandon-3902")
        m:AbandonQuest(3902)
        H.settle(m)
        assert.equal("tr-complete-380", H.cur(ns))
        assert.is_true(E():IsDone("tr-turnin-3901-376"), "accept 3902 stays done after the abandon step")
    end)

    it("observes go / sethearth / vendor / train / fp / fly / hearth on their steps", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-go-brill")
        m:MoveTo(1420, 60.5, 54.0) -- 15 yards away (radius 12)
        H.settle(m)
        assert.equal("tr-go-brill", H.cur(ns))
        m:WalkTo(60.5, 52.6)
        H.settle(m)
        assert.equal("tr-sethearth", H.cur(ns))
        m:SetBindLocation("Brill", 1420, 61.7, 52.0)
        H.settle(m)
        assert.equal("tr-vendor", H.cur(ns))
        m:OpenMerchant({}, 5688)
        m:CloseMerchant()
        H.settle(m)
        assert.equal("tr-train-2", H.cur(ns))
        m:OpenTrainer({}, 246152)
        m:CloseTrainer()
        H.settle(m)
        assert.equal("tr-go-uc", H.cur(ns))
        m:MoveTo(1458, 63.5, 48.5) -- radius 20 on this step
        H.settle(m)
        assert.equal("tr-fp-uc", H.cur(ns))
        m:OpenTaxi({ { name = "Undercity", state = "CURRENT" } }, 4551)
        H.settle(m)
        assert.equal("tr-fly", H.cur(ns), "TAXIMAP_OPENED is enough for fp")
        m:CloseTaxi()
        -- on the flight path: arriving above the destination does not count yet
        m.player.onTaxi = true
        m:MoveTo(1421, 45.6, 42.6)
        H.settle(m)
        assert.equal("tr-fly", H.cur(ns))
        m:Land(1421, 45.6, 42.6)
        H.settle(m)
        assert.equal("tr-hearth", H.cur(ns))
        m:UseHearthstone()
        H.settle(m)
        assert.equal("tr-manual", H.cur(ns))
        local finished = H.record(ns, "STEP_CHANGED")
        E():Next()
        H.settle(m)
        assert.is_nil(E():GetCursor())
        assert.is_nil(E():GetCurrentStep())
        assert.same({}, E():GetUpcoming(5))
        assert.is_nil(finished[#finished][1])
        assert.is_true(H.chatHas(m, "Route finished. Well done!"))
    end)

    it("sethearth: done when the bind location changes or already is the place", function()
        m, ns = H.boot({ mock = { bind = { name = "Deathknell" } } })
        H.playTo(m, ns, "tr-sethearth")
        m.bind = { name = "Undercity" } -- changed without the event (e.g. confirmed elsewhere)
        m:Fire("ZONE_CHANGED")
        H.settle(m)
        assert.equal("tr-vendor", H.cur(ns))

        m, ns = H.boot({ locale = "ruRU", mock = { bind = { name = "Брилл" } } })
        H.playTo(m, ns, "tr-go-brill")
        m:MoveTo(1420, 60.5, 52.5)
        H.settle(m)
        assert.equal("tr-vendor", H.cur(ns), "already bound to the localized place name")
    end)

    it("fast-forwards on a cold start with EMPTY SavedVariables from the game state", function()
        -- 380 in the log, 3902 not: "accept 3902" (abandoned by step 17) is proven only by a LATER done
        -- accept/turnin/complete step -- the reached level of the optional level step 16 is no evidence
        m, ns = H.boot({ player = { level = 2, xp = 600 }, mock = { completedQuests = { 363, 364, 3901, 376 } },
            setup = function(mm) mm:_addToLog(380) end })
        assert.equal("tr-turnin-3901-376", H.cur(ns))
        assert.equal(idx("tr-complete-3901"), E().anchor)
        for i = 1, idx("tr-turnin-3901-376") - 1 do
            if H.STEP_IDS[i] ~= "tr-bg-collect" then
                assert.is_true(E():IsDone(i), "step " .. H.STEP_IDS[i])
            end
        end
        -- a quest-less bg goal of the CURRENT segment is not forwarded: still "along the way"
        assert.is_false(E():IsDone("tr-bg-collect"))
        assert.same({ "tr-bg-collect" }, H.ids(E():GetBackground()))
        -- 380 completed: the complete step anchors, the accept of 3902 and the optional step are forwarded
        m:CompleteObjectives(380)
        H.settle(m)
        assert.equal(idx("tr-complete-380"), E().anchor)
        assert.equal("tr-turnin-380", H.cur(ns))
        assert.is_true(E():IsDone("tr-turnin-3901-376"))
        assert.is_true(E():IsDone("tr-optional"))

        -- in a later segment the bg goals of the segments left behind are forwarded
        m, ns = H.boot({ player = { level = 4, xp = 700 }, mock = { completedQuests = { 363, 364, 3901, 376, 380 } } })
        assert.equal("tr-go-brill", H.cur(ns))
        assert.is_true(E():IsDone("tr-bg-collect"))
        assert.same({}, E():GetBackground())

        -- a fresh character starts at the beginning
        m, ns = H.boot()
        assert.equal("tr-accept-363", H.cur(ns))
    end)

    it("keeps the position across /reload (SavedVariables) and rebuilds it on a cold start", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-vendor")
        local sv = m:ExportSavedVariables()
        assert.equal("tr-vendor", sv.AdventureAtlasCharDB.cursorHintId)
        assert.equal("test-route", sv.AdventureAtlasCharDB.cursorHintRoute)
        local m2, ns2 = H.reload(m)
        assert.equal("tr-vendor", H.cur(ns2), "/reload: high-water mark restored")
        m2:AssertClean()
        local m3, ns3 = H.reload(m, { coldStart = true })
        assert.equal("tr-vendor", H.cur(ns3), "cold start: go / sethearth re-derived from position and bind point")
        m3:AssertClean()
        m:MoveTo(1420, 30, 70)
        local m4, ns4 = H.reload(m, { coldStart = true })
        assert.equal("tr-go-brill", H.cur(ns4), "cold start elsewhere: first transient step after the last stateful one")
        m4:AssertClean()
    end)

    it("Next / Prev / Skip / SetCursor / Reset", function()
        m, ns = H.boot()
        local cdb = m.env.AdventureAtlasCharDB
        E():Next()
        assert.is_true(cdb.manual["tr-accept-363"])
        assert.equal("tr-363-364", H.cur(ns))
        E():Prev() -- undo: the previous step was only done by the manual mark
        assert.is_nil(cdb.manual["tr-accept-363"])
        assert.equal("tr-accept-363", H.cur(ns))
        assert.is_false(E():IsPinned())

        H.playTo(m, ns, "tr-train-1")
        E():Prev() -- truly done step: pinned view, progress unchanged
        assert.equal("tr-363-364", H.cur(ns), "bg step 3 is skipped")
        assert.is_true(E():IsPinned())
        assert.equal(idx("tr-train-1"), E():GetNaturalCursor())
        E():Next() -- moves the pin forward; reaching the natural cursor drops it
        assert.equal("tr-train-1", H.cur(ns))
        assert.is_false(E():IsPinned())

        E():Skip()
        assert.is_true(cdb.skipped["tr-train-1"])
        assert.equal("tr-complete-364", H.cur(ns))

        E():SetCursor(idx("tr-accept-376")) -- forward: skips the not-done steps in between
        assert.equal("tr-accept-376", H.cur(ns))
        assert.is_true(cdb.skipped["tr-complete-364"])
        assert.is_true(cdb.skipped["tr-turnin-364"])
        assert.is_true(cdb.skipped["tr-level-2"])
        assert.is_nil(cdb.skipped["tr-bg-364"], "bg steps are never skipped")
        E():SetCursor(2) -- backward: pinned
        assert.equal("tr-363-364", H.cur(ns))
        assert.is_true(E():IsPinned())
        assert.is_false(E():SetCursor("x"))

        local mark = #m.chat
        E():Reset()
        assert.same({}, cdb.manual)
        assert.same({}, cdb.skipped)
        assert.is_false(E():IsPinned())
        assert.equal("tr-train-1", H.cur(ns), "progress from the game state is kept, the skip is forgotten")
        assert.is_true(H.chatHas(m, "Route progress reset", mark + 1))
    end)

    it("persists manual marks and skips across /reload", function()
        m, ns = H.boot()
        E():Skip()
        E():Next()
        assert.equal("tr-train-1", H.cur(ns))
        local m2, ns2 = H.reload(m)
        assert.equal(H.cur(ns), H.cur(ns2))
        assert.is_true(m2.env.AdventureAtlasCharDB.skipped["tr-accept-363"])
        assert.is_true(m2.env.AdventureAtlasCharDB.manual["tr-363-364"])
        m2:AssertClean()
    end)

    it("recomputes on level-ups (UnitLevel lags behind PLAYER_LEVEL_UP)", function()
        m, ns = H.boot()
        H.playTo(m, ns, "tr-level-2")
        m:GiveXP(400 - m.player.xp)
        H.settle(m)
        assert.equal(2, m.player.level)
        assert.equal("tr-accept-376", H.cur(ns))
    end)
end)
