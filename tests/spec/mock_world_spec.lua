-- Player, units, maps / positions, waypoints, bags, NPC interactions of the WoW: Forever mock.

local Mock = require("mocks.wow")

local function near(a, b, eps) return math.abs(a - b) < (eps or 1e-6) end

describe("mock world", function()
    local m, env

    before_each(function()
        m = Mock.new({ player = { name = "Bones", race = "Scourge", class = "PALADIN", level = 4,
            mapID = 1420, x = 30, y = 70 } })
        env = m.env
    end)

    after_each(function() m:AssertClean() end)

    describe("player and units", function()
        it("reports identity, level and XP", function()
            assert.are.same({ "Undead", "Scourge", 5 }, { env.UnitRace("player") })
            assert.are.same({ "Paladin", "PALADIN", 2 }, { env.UnitClass("player") })
            assert.are.equal("Horde", env.UnitFactionGroup("player"))
            assert.are.equal("Bones", env.UnitName("player"))
            assert.matches("^Player%-", env.UnitGUID("player"))
            assert.are.equal(4, env.UnitLevel("player"))
            assert.are.equal(2100, env.UnitXPMax("player"))
            assert.is_nil(env.GetXPExhaustion())
            m:SetRested(500)
            assert.are.equal(500, env.GetXPExhaustion())
            assert.are.equal(60, env.GetMaxPlayerLevel())
        end)

        it("knows Skyborne factions by raceID", function()
            local horde = Mock.new({ player = { race = "Skyborne", faction = "Horde", class = "DRUID" } })
            assert.are.same({ "Skyborne", "Skyborne", 96 }, { horde.env.UnitRace("player") })
            local ally = Mock.new({ player = { race = "Skyborne", faction = "Alliance", class = "DRUID" } })
            assert.are.equal(95, select(3, ally.env.UnitRace("player")))
            assert.are.equal(11, select(3, ally.env.UnitClass("player")))
        end)

        it("builds creature GUIDs for npc / target and can make them secret", function()
            assert.is_nil(env.UnitGUID("target"))
            assert.is_false(env.UnitExists("target"))
            m:DefineNPC(1568, { name = "Undertaker Mordo", level = 5 })
            m:SetTarget(1568)
            local guid = env.UnitGUID("target")
            assert.are.equal("1568", guid:match("^Creature%-0%-%d+%-%d+%-%d+%-(%d+)%-"))
            assert.are.equal("Undertaker Mordo", env.UnitName("target"))
            assert.are.equal(5, env.UnitLevel("target"))
            assert.are.equal(1, #m:Events("PLAYER_TARGET_CHANGED"))
            m:SetSecretUnits(true)
            local secret = env.UnitGUID("target")
            assert.is_true(env.issecretvalue(secret))
            assert.is_false(env.issecretvalue(env.UnitGUID("player")))
            assert.has_error(function() return secret .. "" end)
            assert.has_error(function() return secret:match("x") end)
        end)

        it("handles combat lockdown and modifier keys", function()
            local during
            local f = env.CreateFrame("Frame")
            f:RegisterEvent("PLAYER_REGEN_DISABLED")
            f:SetScript("OnEvent", function() during = env.InCombatLockdown() end)
            m:EnterCombat()
            assert.is_false(during)                  -- fires before the lockdown starts
            assert.is_true(env.InCombatLockdown())
            m:LeaveCombat()
            assert.is_false(env.InCombatLockdown())
            assert.is_false(env.IsShiftKeyDown())
            m:SetShift(true)
            assert.is_true(env.IsShiftKeyDown())
            assert.are.same({ "MODIFIER_STATE_CHANGED", "LSHIFT", 1 }, m:Events("MODIFIER_STATE_CHANGED")[1])
        end)
    end)

    describe("maps and positions", function()
        it("returns the player map position as a vector and world coordinates", function()
            assert.are.equal(1420, env.C_Map.GetBestMapForUnit("player"))
            local pos = env.C_Map.GetPlayerMapPosition(1420, "player")
            local x, y = pos:GetXY()
            assert.is_true(near(x, 0.30) and near(y, 0.70))
            local cont, world = env.C_Map.GetWorldPosFromMapPos(1420, env.CreateVector2D(0.3, 0.7))
            assert.are.equal(0, cont)
            local wx, wy, _, instance = env.UnitPosition("player")
            assert.are.equal(0, instance)
            assert.is_true(near(wx, world.x) and near(wy, world.y))
            assert.are.same({ 1000, 1000 }, { env.C_Map.GetMapWorldSize(1420) })
            assert.are.equal("Tirisfal Glades", env.C_Map.GetMapInfo(1420).name)
            assert.are.equal(3, env.C_Map.GetMapInfo(1420).mapType)
            assert.is_nil(env.C_Map.GetMapInfo(123456))
        end)

        it("uses 10 yards per map percent by default and supports custom geometry", function()
            assert.is_true(near(m:Distance(1420, 30, 70, 1420, 40, 70), 100))
            assert.is_nil(m:Distance(1420, 30, 70, 1411, 40, 70))      -- other continent
            m:DefineMap(1420, { width = 4000, height = 2000 })
            assert.is_true(near(m:Distance(1420, 30, 70, 1420, 40, 70), 400))
            -- world <-> map round trip through the client API
            local cont, world = env.C_Map.GetWorldPosFromMapPos(1420, env.CreateVector2D(0.25, 0.5))
            local mapID, pos = env.C_Map.GetMapPosFromWorldPos(cont, world, 1420)
            assert.are.equal(1420, mapID)
            assert.is_true(near(pos.x, 0.25) and near(pos.y, 0.5))
        end)

        it("has no world positions on the Forever islands and inside instances", function()
            m:MoveTo(2521, 50, 50)
            assert.are.equal(1, #m:Events("ZONE_CHANGED_NEW_AREA"))
            assert.is_nil(env.UnitPosition("player"))
            assert.is_nil(env.C_Map.GetWorldPosFromMapPos(2521, env.CreateVector2D(0.5, 0.5)))
            assert.is_table(env.C_Map.GetPlayerMapPosition(2521, "player"))
            m:EnterInstance("Ragefire Chasm", "party", nil)
            assert.is_nil(env.C_Map.GetBestMapForUnit("player"))
            assert.is_nil(env.C_Map.GetPlayerMapPosition(2521, "player"))
            assert.is_true((env.IsInInstance()))
        end)

        it("faces and walks towards a point, advancing the clock", function()
            m:FaceTowards(30, 60)                                  -- due north
            assert.is_true(near(env.GetPlayerFacing(), 0))
            m:FaceTowards(20, 70)                                  -- due west
            assert.is_true(near(env.GetPlayerFacing(), math.pi / 2))
            local t0 = env.GetTime()
            m:WalkTo(30, 63, 7)                                    -- 70 yards at 7 yd/s
            assert.is_true(near(m.player.y, 63, 1e-6))
            assert.is_true(near(env.GetTime() - t0, 10, 0.06))
        end)
    end)

    describe("waypoints", function()
        it("sets, super-tracks and clears a user waypoint", function()
            assert.is_true(env.C_Map.CanSetUserWaypointOnMap(1420))
            local point = env.UiMapPoint.CreateFromCoordinates(1420, 0.5, 0.25)
            assert.is_true(env.C_Map.SetUserWaypoint(point))
            env.C_SuperTrack.SetSuperTrackedUserWaypoint(true)
            assert.is_true(env.C_Map.HasUserWaypoint())
            assert.is_true(env.C_SuperTrack.IsSuperTrackingUserWaypoint())
            local got = env.C_Map.GetUserWaypoint()
            assert.are.equal(1420, got.uiMapID)
            assert.are.equal(0.25, got.position.y)
            env.C_Map.ClearUserWaypoint()
            assert.is_false(env.C_Map.HasUserWaypoint())
            assert.is_false(env.C_SuperTrack.IsSuperTrackingUserWaypoint())
            assert.are.equal(2, #m:Events("USER_WAYPOINT_UPDATED"))
            assert.are.equal(2, #m:Events("SUPER_TRACKING_CHANGED"))
        end)

        it("rejects percent coordinates and maps that disallow waypoints", function()
            assert.has_error(function()
                env.C_Map.SetUserWaypoint(env.UiMapPoint.CreateFromCoordinates(1420, 50, 25))
            end)
            m:DefineMap(1420, { canWaypoint = false })
            assert.is_false(env.C_Map.CanSetUserWaypointOnMap(1420))
            assert.has_error(function()
                env.C_Map.SetUserWaypoint(env.UiMapPoint.CreateFromCoordinates(1420, 0.5, 0.5))
            end)
            m:ClearDiagnostics()
        end)
    end)

    describe("bags and items", function()
        it("counts items, lays out the backpack and loads item data", function()
            m:DefineItem(6948, { name = "Hearthstone", icon = 134414 })
            m:AddItem(6948)
            m:AddItem(2672, 3)
            assert.are.equal(1, env.C_Item.GetItemCount(6948))
            assert.are.equal(3, env.C_Item.GetItemCount("item:2672"))
            assert.are.equal(6948, env.C_Container.GetContainerItemID(0, 1))
            assert.are.equal(3, env.C_Container.GetContainerItemInfo(0, 2).stackCount)
            assert.are.equal(14, (env.C_Container.GetContainerNumFreeSlots(0)))
            assert.are.equal(2, #m:Events("BAG_UPDATE_DELAYED"))
            m:DefineItem(5000, { name = "Uncached", cached = false })
            assert.is_nil(env.C_Item.GetItemNameByID(5000))
            m:Advance(0)
            assert.are.same({ "ITEM_DATA_LOAD_RESULT", 5000, true }, m:Events("ITEM_DATA_LOAD_RESULT")[1])
            assert.are.equal("Uncached", env.C_Item.GetItemNameByID(5000))
            m:RemoveItem(2672, 3)
            assert.are.equal(0, env.C_Item.GetItemCount(2672))
        end)
    end)

    describe("NPC services", function()
        it("trains spells", function()
            m:SetMoney(100)
            m:OpenTrainer({ services = { { name = "Blessing of Might", rank = "Rank 1", spellID = 19740, cost = 100 },
                { name = "Holy Light", rank = "Rank 2", category = "unavailable", spellID = 639 } } }, 925)
            assert.are.equal(1, #m:Events("TRAINER_SHOW"))
            assert.are.equal(2, env.GetNumTrainerServices())
            assert.are.equal("available", select(3, env.GetTrainerServiceInfo(1)))
            env.BuyTrainerService(1)
            assert.is_true(env.C_SpellBook.IsSpellKnown(19740))
            assert.are.equal(0, env.GetMoney())
            assert.are.same({ "LEARNED_SPELL_IN_SKILL_LINE", 19740, 1, false }, m:Events("LEARNED_SPELL_IN_SKILL_LINE")[1])
            env.CloseTrainer()
            assert.are.equal(1, #m:Events("TRAINER_CLOSED"))
            assert.are.same({ "PLAYER_INTERACTION_MANAGER_FRAME_HIDE", env.Enum.PlayerInteractionType.Trainer },
                m:Events("PLAYER_INTERACTION_MANAGER_FRAME_HIDE")[1])
        end)

        it("flies: TAXIMAP_OPENED, TakeTaxiNode, landing", function()
            m:OpenTaxi({ { name = "Undercity", state = "CURRENT" },
                { name = "The Sepulcher", state = "REACHABLE", mapID = 1421, destX = 45, destY = 42, flightTime = 30 } }, 4551)
            assert.are.same({ "TAXIMAP_OPENED", 1 }, m:Events("TAXIMAP_OPENED")[1])
            assert.are.equal("CURRENT", env.TaxiNodeGetType(1))
            assert.are.equal(2, #env.C_TaxiMap.GetAllTaxiNodes(1458))
            env.TakeTaxiNode(2)
            assert.is_true(env.UnitOnTaxi("player"))
            assert.are.equal(1, #m:Events("TAXIMAP_CLOSED"))
            m:Advance(31)
            assert.is_false(env.UnitOnTaxi("player"))
            assert.are.equal(1421, env.C_Map.GetBestMapForUnit("player"))
            assert.are.equal(1, #m:Events("PLAYER_CONTROL_GAINED"))
        end)

        it("binds the hearthstone and teleports with it", function()
            m:OpenBinder("Brill", 6741, 1420, 61, 52)
            assert.are.same({ "CONFIRM_BINDER", "Brill" }, m:Events("CONFIRM_BINDER")[1])
            env.C_PlayerInteractionManager.ConfirmationInteraction(env.Enum.PlayerInteractionType.Binder)
            assert.are.equal("Brill", env.GetBindLocation())
            assert.are.equal(1, #m:Events("HEARTHSTONE_BOUND"))
            m:MoveTo(1421, 50, 50)
            m:UseHearthstone()
            assert.are.equal(8690, m:Events("UNIT_SPELLCAST_SUCCEEDED")[1][4])
            assert.are.equal(1420, m.player.mapID)
        end)

        it("opens and closes a vendor", function()
            m:OpenMerchant({ items = { { itemID = 159, price = 25 } } }, 2134)
            assert.are.equal(1, env.GetMerchantNumItems())
            env.CloseMerchant()
            assert.are.equal(1, #m:Events("MERCHANT_CLOSED"))
            assert.is_nil(m.interaction)
        end)
    end)
end)
